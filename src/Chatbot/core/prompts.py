    - "MajorInfo" (学院 / 专业介绍)
    - "Course" (课程安排 / 选课 / 考试 / 成绩)
    - "StudentStatus" (学籍管理 / 请假 / 转专业 / 处分)
    - "CampusLife" (宿舍 / 饮食 / 校园卡 / 网络 / 校园生活)
